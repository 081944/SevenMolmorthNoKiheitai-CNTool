#!/usr/bin/env python3
"""Extract and rebuild Seven Warriors (SLPS-25025) ITE images.

ITE stores an RGBA image as 64x32 tiles.  Each tile is a headerless PS2 IPU
IDEC/MPEG-2 intra bitstream and expands to exactly 0x2000 bytes of RGB32 data.

The tool supports standalone ITE files and ITE images embedded in FHN files.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import shutil
import struct
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

from PIL import Image

from ite_mpeg2 import (
    bits_to_bytes,
    build_idec_from_mpeg2,
    split_idec_into_slices,
)


MAGIC = b"ITE\x00"
TILE_W = 64
TILE_H = 32
TILE_RGBA_SIZE = TILE_W * TILE_H * 4
OFFSET_MASK = 0x3FFFFFFF
# The GS blending equation uses a 7-bit texture alpha coefficient: 0x7f/0x80
# is visually opaque. PNG uses the conventional 0..255 alpha range.
GS_ALPHA_OPAQUE = 0x7F

# A 64x32 MPEG-2 I-picture header generated by FFmpeg.  The picture coding
# extension selects the same modes as IPU_CTRL=0x01600000: 8-bit intra DC,
# normal scan, alternate intra VLC, and nonlinear quantizer scale.
MPEG2_I_HEADER_64X32 = bytes.fromhex(
    "000001b304002013ffffe018"
    "000001b5148a00010000"
    "000001b800080040"
    "00000100000ffff8"
    "000001b58ffff35980"
)


@dataclass(frozen=True)
class Tile:
    index: int
    x: int
    y: int
    kind: int
    offset: int
    end: int
    data: bytes


@dataclass(frozen=True)
class Ite:
    width: int
    height: int
    reserved: int
    tiles_x: int
    tiles_y: int
    tiles: tuple[Tile, ...]


class IteError(ValueError):
    pass


def _u32(data: bytes, offset: int) -> int:
    return int.from_bytes(data[offset:offset + 4], "little")


def parse_ite(data: bytes) -> Ite:
    if len(data) < 0x10 or data[:4] != MAGIC:
        raise IteError("not an ITE file")
    width = _u32(data, 4)
    height = _u32(data, 8)
    reserved = _u32(data, 12)
    if not (1 <= width <= 16384 and 1 <= height <= 16384):
        raise IteError(f"invalid dimensions: {width}x{height}")

    tiles_x = math.ceil(width / TILE_W)
    tiles_y = math.ceil(height / TILE_H)
    count = tiles_x * tiles_y
    table_end = 0x10 + count * 4
    if table_end > len(data):
        raise IteError("truncated tile offset table")

    raw_offsets = [_u32(data, 0x10 + i * 4) for i in range(count)]
    offsets = [value & OFFSET_MASK for value in raw_offsets]
    for i, offset in enumerate(offsets):
        if not (table_end <= offset < len(data)):
            raise IteError(f"tile {i} has invalid offset 0x{offset:x}")

    tiles = []
    for i, (raw, offset) in enumerate(zip(raw_offsets, offsets)):
        later = [candidate for candidate in offsets if candidate > offset]
        end = min(later) if later else len(data)
        if end <= offset:
            raise IteError(f"tile {i} has an empty/overlapping range")
        tiles.append(Tile(
            index=i,
            x=i % tiles_x,
            y=i // tiles_x,
            kind=raw >> 30,
            offset=offset,
            end=end,
            data=data[offset:end],
        ))
    return Ite(width, height, reserved, tiles_x, tiles_y, tuple(tiles))


def _find_ffmpeg(explicit: Path | None = None) -> Path:
    candidates = []
    if explicit is not None:
        candidates.append(explicit)
    if os.environ.get("IMAGEIO_FFMPEG_EXE"):
        candidates.append(Path(os.environ["IMAGEIO_FFMPEG_EXE"]))
    candidates.append(
        Path(__file__).resolve().parents[1]
        / "temp/deps/imageio_ffmpeg/binaries/ffmpeg-win-x86_64-v7.1.exe"
    )
    try:
        import imageio_ffmpeg
        candidates.append(Path(imageio_ffmpeg.get_ffmpeg_exe()))
    except Exception:
        pass
    found = shutil.which("ffmpeg")
    if found:
        candidates.append(Path(found))
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    raise IteError("FFmpeg not found; pass --ffmpeg or set IMAGEIO_FFMPEG_EXE")


def wrap_idec_as_mpeg2(tile_data: bytes, kind: int = 0, plane: int = 0) -> bytes:
    """Repack one headerless IDEC stream as a standard MPEG-2 I-picture.

    ITE runs one slice across all eight macroblocks and preserves DC prediction
    across both rows.  Standard decoders reject that layout, so each macroblock
    becomes an independent slice and its DC values are rebased to predictor 128.
    AC coefficients are copied bit-for-bit.
    """
    marker = tile_data.find(b"\x00\x00\x01\xb0")
    if marker < 0:
        raise IteError("tile has no ITE end marker 00 00 01 B0")
    payload = tile_data[:marker]
    parts = [MPEG2_I_HEADER_64X32]
    macroblock_count = 8 if kind == 2 else 16
    for row, _column, _qscale, slice_bits in split_idec_into_slices(
            payload, plane, macroblock_count):
        parts.append(b"\x00\x00\x01" + bytes([row + 1]))
        parts.append(bits_to_bytes(slice_bits))
    parts.append(b"\x00\x00\x01\xb7")
    return b"".join(parts)


def _decode_tile_plane(tile_data: bytes, ffmpeg: Path, kind: int, plane: int) -> bytes:
    wrapped = wrap_idec_as_mpeg2(tile_data, kind, plane)
    with tempfile.TemporaryDirectory(prefix="ite_7w_") as tmp_name:
        tmp = Path(tmp_name)
        stream_path = tmp / "tile.m2v"
        rgba_path = tmp / "tile.rgba"
        stream_path.write_bytes(wrapped)
        proc = subprocess.run([
            str(ffmpeg), "-y", "-hide_banner", "-loglevel", "error",
            # ITE deliberately runs one IDEC slice across both macroblock rows.
            # FFmpeg decodes the pixels correctly but reports an end mismatch;
            # its default error concealment would replace the frame with gray.
            "-err_detect", "ignore_err", "-ec", "0",
            "-f", "mpegvideo", "-i", str(stream_path),
            "-frames:v", "1", "-f", "rawvideo", "-pix_fmt", "rgba",
            str(rgba_path),
        ], capture_output=True, text=True)
        if proc.returncode != 0:
            detail = proc.stderr.strip() or f"exit code {proc.returncode}"
            raise IteError(f"FFmpeg could not decode tile: {detail}")
        rgba = rgba_path.read_bytes() if rgba_path.is_file() else b""
    if len(rgba) != TILE_RGBA_SIZE:
        raise IteError(
            f"decoded tile has {len(rgba)} bytes, expected {TILE_RGBA_SIZE}"
        )
    return rgba


def decode_tile(tile_data: bytes, ffmpeg: Path, kind: int = 0) -> bytes:
    # Some ITEs deduplicate transparent tiles by pointing several table entries
    # at one 16-byte zero block instead of storing an IDEC stream.
    if tile_data and not any(tile_data):
        return b"\x00" * TILE_RGBA_SIZE
    color = _decode_tile_plane(tile_data, ffmpeg, kind, 0)
    if kind == 2:
        return color
    mask = _decode_tile_plane(tile_data, ffmpeg, kind, 1)
    rgba = bytearray(color)
    for offset in range(0, len(rgba), 4):
        rgba[offset + 3] = min(
            255, (mask[offset] * 255 + GS_ALPHA_OPAQUE // 2) // GS_ALPHA_OPAQUE
        )
    return bytes(rgba)


def render_ite(ite: Ite, ffmpeg: Path) -> Image.Image:
    canvas = Image.new("RGBA", (ite.tiles_x * TILE_W, ite.tiles_y * TILE_H))
    for tile in ite.tiles:
        rgba = decode_tile(tile.data, ffmpeg, tile.kind)
        image = Image.frombytes("RGBA", (TILE_W, TILE_H), rgba)
        canvas.paste(image, (tile.x * TILE_W, tile.y * TILE_H))
    return canvas.crop((0, 0, ite.width, ite.height))


def _encode_plane(rgba: bytes, ffmpeg: Path, quantizer: int) -> bytes:
    with tempfile.TemporaryDirectory(prefix="ite_7w_enc_") as tmp_name:
        tmp = Path(tmp_name)
        rgba_path = tmp / "tile.rgba"
        stream_path = tmp / "tile.m2v"
        rgba_path.write_bytes(rgba)
        proc = subprocess.run([
            str(ffmpeg), "-y", "-hide_banner", "-loglevel", "error",
            "-f", "rawvideo", "-pix_fmt", "rgba", "-s:v", "64x32",
            "-i", str(rgba_path), "-frames:v", "1",
            "-c:v", "mpeg2video", "-pix_fmt", "yuv420p",
            "-g", "1", "-bf", "0", "-threads", "1",
            "-intra_vlc", "1", "-non_linear_quant", "1",
            "-alternate_scan", "0", "-qmin", str(quantizer),
            "-qmax", str(quantizer), "-q:v", str(quantizer),
            "-f", "mpeg2video", str(stream_path),
        ], capture_output=True, text=True)
        if proc.returncode != 0:
            detail = proc.stderr.strip() or f"exit code {proc.returncode}"
            raise IteError(f"FFmpeg could not encode tile: {detail}")
        return stream_path.read_bytes()


def encode_tile(image: Image.Image, ffmpeg: Path, quantizer: int) -> bytes:
    image = image.convert("RGBA")
    color = image.tobytes()
    mask = bytearray(TILE_RGBA_SIZE)
    for pixel in range(TILE_W * TILE_H):
        alpha = color[pixel * 4 + 3]
        gs_alpha = (alpha * GS_ALPHA_OPAQUE + 127) // 255
        mask[pixel * 4:pixel * 4 + 4] = bytes((gs_alpha, gs_alpha, gs_alpha, 255))
    color_mpeg2 = _encode_plane(color, ffmpeg, quantizer)
    mask_mpeg2 = _encode_plane(bytes(mask), ffmpeg, quantizer)
    return build_idec_from_mpeg2(color_mpeg2, mask_mpeg2)


def rebuild_ite(original: bytes, image: Image.Image, ffmpeg: Path,
                quantizer: int) -> bytes:
    ite = parse_ite(original)
    if image.size != (ite.width, ite.height):
        raise IteError(
            f"PNG size {image.width}x{image.height} does not match "
            f"ITE size {ite.width}x{ite.height}"
        )
    image = image.convert("RGBA")
    tile_data = []
    for tile_y in range(ite.tiles_y):
        for tile_x in range(ite.tiles_x):
            tile = Image.new("RGBA", (TILE_W, TILE_H), (0, 0, 0, 0))
            crop = image.crop((
                tile_x * TILE_W,
                tile_y * TILE_H,
                min((tile_x + 1) * TILE_W, ite.width),
                min((tile_y + 1) * TILE_H, ite.height),
            ))
            tile.paste(crop, (0, 0))
            tile_data.append(encode_tile(tile, ffmpeg, quantizer))

    table_end = 0x10 + len(tile_data) * 4
    data_start = (table_end + 15) & ~15
    offsets = []
    cursor = data_start
    for block in tile_data:
        offsets.append(cursor)  # type 0: color + mask planes
        cursor += len(block)
    out = bytearray()
    out += MAGIC
    out += struct.pack("<III", ite.width, ite.height, ite.reserved)
    out += struct.pack(f"<{len(offsets)}I", *offsets)
    out += b"\x00" * (data_start - len(out))
    out += b"".join(tile_data)
    return bytes(out)


def _fhn_resource_ranges(data: bytes) -> list[tuple[int, int]]:
    """Return (offset, size) pairs from the FHN resource offset table."""
    if len(data) < 8:
        return []
    count = _u32(data, 0)
    table_end = 4 + count * 4
    if not (1 <= count <= 65536) or table_end > len(data):
        return []
    offsets = [_u32(data, 4 + index * 4) for index in range(count)]
    if offsets[0] < table_end or offsets[-1] >= len(data):
        return []
    if any(left >= right for left, right in zip(offsets, offsets[1:])):
        return []
    ends = offsets[1:] + [len(data)]
    return [(offset, end - offset) for offset, end in zip(offsets, ends)]


def find_embedded_ites(data: bytes) -> list[tuple[int, int]]:
    resources = _fhn_resource_ranges(data)
    if resources:
        return [
            (offset, size)
            for offset, size in resources
            if data[offset:offset + 4] == MAGIC
        ]

    # Fallback for headerless containers encountered during format research.
    positions = []
    at = 0
    while True:
        at = data.find(MAGIC, at)
        if at < 0:
            break
        positions.append(at)
        at += 4
    result = []
    for offset in positions:
        header = data[offset:]
        if len(header) < 0x10:
            continue
        width, height = _u32(header, 4), _u32(header, 8)
        count = math.ceil(width / TILE_W) * math.ceil(height / TILE_H)
        if not (1 <= count <= 65536) or 0x10 + count * 4 > len(header):
            continue
        tile_offsets = [
            _u32(header, 0x10 + index * 4) & OFFSET_MASK
            for index in range(count)
        ]
        last = max(tile_offsets)
        marker = data.find(b"\x00\x00\x01\xb0", offset + last)
        if marker < 0:
            continue
        size = ((marker + 4 - offset) + 15) & ~15
        result.append((offset, size))
    return result


def cmd_info(args: argparse.Namespace) -> None:
    data = args.input.read_bytes()
    ite = parse_ite(data)
    result = {
        "file": str(args.input),
        "width": ite.width,
        "height": ite.height,
        "reserved": ite.reserved,
        "tiles_x": ite.tiles_x,
        "tiles_y": ite.tiles_y,
        "tiles": [
            {
                "index": tile.index,
                "x": tile.x,
                "y": tile.y,
                "type": tile.kind,
                "offset": tile.offset,
                "size": tile.end - tile.offset,
            }
            for tile in ite.tiles
        ],
    }
    print(json.dumps(result, ensure_ascii=False, indent=2))


def cmd_extract(args: argparse.Namespace) -> None:
    ffmpeg = _find_ffmpeg(args.ffmpeg)
    ite = parse_ite(args.input.read_bytes())
    image = render_ite(ite, ffmpeg)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    image.save(args.output)
    print(f"extracted {ite.width}x{ite.height}, {len(ite.tiles)} tiles -> {args.output}")


def cmd_write(args: argparse.Namespace) -> None:
    ffmpeg = _find_ffmpeg(args.ffmpeg)
    original = args.input.read_bytes()
    image = Image.open(args.png)
    rebuilt = rebuild_ite(original, image, ffmpeg, args.quantizer)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(rebuilt)
    print(f"rebuilt {image.width}x{image.height}, {len(rebuilt)} bytes -> {args.output}")


def cmd_fhn_info(args: argparse.Namespace) -> None:
    data = args.input.read_bytes()
    entries = find_embedded_ites(data)
    for index, (offset, size) in enumerate(entries):
        ite = parse_ite(data[offset:offset + size])
        print(
            f"{index:2} offset=0x{offset:08x} size=0x{size:x} ({size}) "
            f"dimensions={ite.width}x{ite.height} tiles={len(ite.tiles)}"
        )
    print(f"embedded_ite={len(entries)}")


def _embedded_entry(path: Path, index: int) -> tuple[bytes, list[tuple[int, int]], int, int]:
    data = path.read_bytes()
    entries = find_embedded_ites(data)
    if not (0 <= index < len(entries)):
        raise IteError(f"embedded ITE index {index} is out of range (count={len(entries)})")
    offset, size = entries[index]
    return data, entries, offset, size


def cmd_fhn_extract(args: argparse.Namespace) -> None:
    data, _entries, offset, size = _embedded_entry(args.input, args.index)
    ffmpeg = _find_ffmpeg(args.ffmpeg)
    ite = parse_ite(data[offset:offset + size])
    image = render_ite(ite, ffmpeg)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    image.save(args.output)
    print(f"extracted FHN ITE {args.index} at 0x{offset:x} -> {args.output}")


def cmd_fhn_write(args: argparse.Namespace) -> None:
    data, entries, offset, old_size = _embedded_entry(args.input, args.index)
    ffmpeg = _find_ffmpeg(args.ffmpeg)
    image = Image.open(args.png)
    rebuilt = rebuild_ite(
        data[offset:offset + old_size], image, ffmpeg, args.quantizer
    )
    can_resize = offset + old_size == len(data)
    if not can_resize and len(rebuilt) > old_size:
        raise IteError(
            f"rebuilt ITE is {len(rebuilt) - old_size} bytes too large for its FHN slot"
        )
    if not can_resize:
        rebuilt += b"\x00" * (old_size - len(rebuilt))
    output = data[:offset] + rebuilt + data[offset + old_size:]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(output)
    print(
        f"replaced FHN ITE {args.index} at 0x{offset:x}: "
        f"{old_size} -> {len(rebuilt)} bytes, output={args.output}"
    )


def cmd_verify(args: argparse.Namespace) -> None:
    ffmpeg = _find_ffmpeg(args.ffmpeg)
    ite = parse_ite(args.input.read_bytes())
    for tile in ite.tiles:
        decode_tile(tile.data, ffmpeg, tile.kind)
    print(f"ok: {ite.width}x{ite.height}, {len(ite.tiles)} tiles decode successfully")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    info = sub.add_parser("info", help="show ITE dimensions and tile table")
    info.add_argument("input", type=Path)
    info.set_defaults(func=cmd_info)

    extract = sub.add_parser("extract", help="decode one ITE to PNG")
    extract.add_argument("input", type=Path)
    extract.add_argument("output", type=Path)
    extract.add_argument("--ffmpeg", type=Path)
    extract.set_defaults(func=cmd_extract)

    write = sub.add_parser("write", help="encode a PNG as a rebuilt ITE")
    write.add_argument("input", type=Path, help="original ITE")
    write.add_argument("png", type=Path, help="edited PNG of the same dimensions")
    write.add_argument("output", type=Path)
    write.add_argument("--quantizer", type=int, default=4, choices=range(1, 29))
    write.add_argument("--ffmpeg", type=Path)
    write.set_defaults(func=cmd_write)

    fhn_info = sub.add_parser("fhn-info", help="list ITE images embedded in an FHN")
    fhn_info.add_argument("input", type=Path)
    fhn_info.set_defaults(func=cmd_fhn_info)

    fhn_extract = sub.add_parser("fhn-extract", help="extract one embedded FHN ITE")
    fhn_extract.add_argument("input", type=Path)
    fhn_extract.add_argument("index", type=int)
    fhn_extract.add_argument("output", type=Path)
    fhn_extract.add_argument("--ffmpeg", type=Path)
    fhn_extract.set_defaults(func=cmd_fhn_extract)

    fhn_write = sub.add_parser("fhn-write", help="replace one embedded FHN ITE")
    fhn_write.add_argument("input", type=Path)
    fhn_write.add_argument("index", type=int)
    fhn_write.add_argument("png", type=Path)
    fhn_write.add_argument("output", type=Path)
    fhn_write.add_argument("--quantizer", type=int, default=4, choices=range(1, 29))
    fhn_write.add_argument("--ffmpeg", type=Path)
    fhn_write.set_defaults(func=cmd_fhn_write)

    verify = sub.add_parser("verify", help="decode every tile and validate the stream")
    verify.add_argument("input", type=Path)
    verify.add_argument("--ffmpeg", type=Path)
    verify.set_defaults(func=cmd_verify)
    return parser


def main() -> None:
    args = build_parser().parse_args()
    try:
        args.func(args)
    except (IteError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        raise SystemExit(2) from exc


if __name__ == "__main__":
    main()
